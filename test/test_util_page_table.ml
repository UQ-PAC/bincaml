open Bincaml_util


let%expect_test "page range" =
  let tbl = Page_table.create () in
  let r =
    Page_table.page_range_iter tbl (Z.of_int 1234) (Z.of_int 1242)
    |> Iter.to_string ~sep:", " Z.to_string
  in
  print_endline r;
  [%expect {| 1024 |}]

let%expect_test "page range multi" =
  let tbl = Page_table.create () in
  let r =
    Page_table.page_range_iter tbl (Z.of_int 100) (Z.of_int 5000)
    |> Iter.to_string ~sep:", " Z.to_string
  in
  print_endline r;
  [%expect {| 0, 1024, 2048, 3072, 4096 |}]

let%expect_test "page" =
  let tbl = Page_table.create () in
  let obits = Bitvec.create ~size:64 (Z.of_bits "abcdefgh") in
  Page_table.write_bv tbl ~addr:(Z.of_int 0x0c8) @@ obits;
  Page_table.write_bv tbl ~addr:(Z.of_int 0x0ce) obits;
  let read = Page_table.read_bv tbl ~addr:(Z.of_int 0x0c8) ~nbits:(14 * 8) in
  let read_bv =
    read |> Bitvec.value |> Z.to_bits |> fun s -> String.sub s 0 14
  in
